begin;

do $$
begin
  if to_regclass('public.sync_logs') is not null
     and to_regclass('public.sync_log') is null then
    alter table public.sync_logs rename to sync_log;
  end if;
end
$$;

create table if not exists public.sync_log (
  sync_id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  sync_timestamp timestamptz not null default now(),
  status text not null,
  records integer not null default 0,
  "sync" integer not null default 0
);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_log_id'
  ) and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_id'
  ) then
    alter table public.sync_log rename column sync_log_id to sync_id;
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'created_at'
  ) and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_timestamp'
  ) then
    alter table public.sync_log rename column created_at to sync_timestamp;
  end if;
end
$$;

alter table public.sync_log
  add column if not exists user_id uuid references auth.users(id) on delete set null default auth.uid(),
  add column if not exists sync_timestamp timestamptz not null default now(),
  add column if not exists status text not null default 'success',
  add column if not exists records integer not null default 0,
  add column if not exists "sync" integer not null default 0;

alter table public.sync_log enable row level security;
revoke all on public.sync_log from anon, authenticated;
grant usage on schema public to authenticated;
grant insert on public.sync_log to authenticated;

drop policy if exists nutrigrid_sync_logs_insert_own on public.sync_log;
create policy nutrigrid_sync_logs_insert_own on public.sync_log
  for insert to authenticated
  with check (user_id = (select auth.uid()));

do $$
declare
  sequence_name text;
begin
  sequence_name := pg_get_serial_sequence('public.sync_log', 'sync_id');
  if sequence_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', sequence_name);
  end if;
end
$$;

commit;
