create table if not exists public.sync_log (
  sync_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  sync_timestamp timestamptz not null default now(),
  status text not null,
  records integer not null default 0,
  "sync" integer not null default 0
);

-- Rename columns if the earlier plural-table script already created them.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_log_id'
  ) and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_id'
  ) then
    alter table public.sync_log rename column sync_log_id to sync_id;
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'created_at'
  ) and not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'sync_log'
      and column_name = 'sync_timestamp'
  ) then
    alter table public.sync_log rename column created_at to sync_timestamp;
  end if;
end
$$;

alter table public.sync_log
  add column if not exists sync_timestamp timestamptz not null default now(),
  add column if not exists status text not null default 'success',
  add column if not exists records integer not null default 0,
  add column if not exists "sync" integer not null default 0;

create index if not exists sync_log_user_timestamp_idx
  on public.sync_log (user_id, sync_timestamp desc);

