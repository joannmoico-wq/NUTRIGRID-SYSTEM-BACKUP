-- Add missing NutriGrid columns and task/sync-log tables without dropping
-- existing category data or changing the existing UUID primary keys.
-- Tasks use the ERD fields plus title/description/due_date/created_at required
-- by the current app. SyncLog uses only the fields visible in the ERD.
-- Run in Supabase SQL Editor as the project owner.

begin;

alter table public.residents
  add column if not exists purok text;
alter table public.environmental_sanitation
  add column if not exists purok text;
alter table public.infant_feeding
  add column if not exists purok text;
alter table public.lactating_women
  add column if not exists purok text;
alter table public.pregnant_women
  add column if not exists purok text;
alter table public.monthly_natality
  add column if not exists purok text;
alter table public.monthly_natality
  add column if not exists birth_weight numeric,
  add column if not exists sex text,
  add column if not exists iron_status text,
  add column if not exists remarks text;

-- Allow each approved field worker to restore only their own previously synced PWA records.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'residents',
    'environmental_sanitation',
    'infant_feeding',
    'lactating_women',
    'pregnant_women',
    'monthly_natality'
  ]
  loop
    execute format(
      'alter table public.%I add column if not exists created_by_user_id uuid references auth.users(id) on delete set null',
      table_name
    );
    execute format('grant select on public.%I to authenticated', table_name);
    execute format(
      'drop policy if exists nutrigrid_member_read_own on public.%I',
      table_name
    );
    execute format(
      'create policy nutrigrid_member_read_own on public.%I for select to authenticated using (public.is_approved_staff() and (created_by_user_id = (select auth.uid()) or data->>''created_by_user_id'' = (select auth.uid())::text))',
      table_name
    );
  end loop;
end
$$;

-- Remove the broad policy from the previous CRUD script, if it was run.
-- Keep the existing approved read/insert/update policies in place.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'residents',
    'environmental_sanitation',
    'infant_feeding',
    'lactating_women',
    'pregnant_women',
    'monthly_natality'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists nutrigrid_authenticated_crud on public.%I', table_name);
    execute format(
      'grant select, insert, update, delete on public.%I to authenticated',
      table_name
    );
    execute format('drop policy if exists "approved delete" on public.%I', table_name);
    execute format(
      'create policy "approved delete" on public.%I for delete to authenticated using (public.is_approved_staff())',
      table_name
    );
  end loop;
end
$$;

create table if not exists public.tasks (
  task_id bigint generated by default as identity primary key,
  assigned_to_user_id uuid not null references auth.users(id) on delete cascade,
  priority text not null default 'Normal'
    check (priority in ('High', 'Normal', 'Low')),
  status text not null default 'Pending'
    check (status in ('Pending', 'In Progress', 'Completed')),
  purok text,
  completed_at timestamptz,
  title text not null default 'Field visit',
  description text,
  due_date date,
  created_at timestamptz not null default now()
);

