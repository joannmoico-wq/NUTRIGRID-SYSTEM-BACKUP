create or replace function public.nutrigrid_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and lower(role) = 'admin'
      and approved is true
  );
$$;

revoke all on function public.nutrigrid_is_admin() from public;
grant execute on function public.nutrigrid_is_admin() to authenticated;

grant select (id, full_name, email, role, approved) on public.profiles to authenticated;
drop policy if exists nutrigrid_admin_read_approved_bhws on public.profiles;
create policy nutrigrid_admin_read_approved_bhws on public.profiles
  for select to authenticated
  using (
    public.nutrigrid_is_admin()
    and role = 'field_worker'
    and approved is true
  );

create or replace function public.get_approved_bhws()
returns table (id uuid, full_name text, email text)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.full_name, p.email
  from public.profiles p
  where public.nutrigrid_is_admin()
    and p.role = 'field_worker'
    and p.approved is true
    and exists (
      select 1
      from public.allowed_emails ae
      where lower(ae.email) = lower(p.email)
    )
  order by p.full_name nulls last, p.email;
$$;

revoke all on function public.get_approved_bhws() from public;
grant execute on function public.get_approved_bhws() to authenticated;

alter table public.profiles
