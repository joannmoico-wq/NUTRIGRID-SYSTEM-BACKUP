create table if not exists public.monthly_report (
  monthly_report_id bigint generated by default as identity primary key,
  slug text not null,
  indicator text not null,
  category text,
  subcategory text,
  group_label text,
  is_header boolean not null default false,
  sort_order integer not null default 0,
  barangay text not null default 'ALAWIHAO',
  report_year integer not null default extract(year from current_date)::integer,
  m1_male integer not null default 0 check (m1_male >= 0),
  m1_female integer not null default 0 check (m1_female >= 0),
  m2_male integer not null default 0 check (m2_male >= 0),
  m2_female integer not null default 0 check (m2_female >= 0),
  m3_male integer not null default 0 check (m3_male >= 0),
  m3_female integer not null default 0 check (m3_female >= 0),
  total_male integer generated always as (m1_male + m2_male + m3_male) stored,
  total_female integer generated always as (m1_female + m2_female + m3_female) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint monthly_report_year_valid check (report_year between 2000 and 2200),
  constraint monthly_report_barangay_year_slug_key unique (barangay, report_year, slug)
);

create index if not exists monthly_report_year_sort_idx
  on public.monthly_report (barangay, report_year, sort_order);

create or replace function public.set_monthly_report_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists monthly_report_updated_at on public.monthly_report;
create trigger monthly_report_updated_at
  before update on public.monthly_report
  for each row execute function public.set_monthly_report_updated_at();

alter table public.monthly_report enable row level security;

grant select, insert, update, delete on public.monthly_report to authenticated;
grant usage, select on sequence public.monthly_report_monthly_report_id_seq to authenticated;

drop policy if exists nutrigrid_monthly_report_admin_all on public.monthly_report;
create policy nutrigrid_monthly_report_admin_all on public.monthly_report
  for all to authenticated
  using (public.nutrigrid_is_admin())
  with check (public.nutrigrid_is_admin());
