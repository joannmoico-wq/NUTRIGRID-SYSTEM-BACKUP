insert into public.monthly_report (
  slug,
  indicator,
  category,
  subcategory,
  group_label,
  is_header,
  sort_order,
  barangay,
  report_year,
  report_quarter,
  month_1_name,
  month_2_name,
  month_3_name
)
select
  template.slug,
  template.indicator,
  template.indicator,
  case when template.is_header then null else template.indicator end,
  template.indicator,
  template.is_header,
  template.sort_order,
  'ALAWIHAO',
  extract(year from current_date)::integer,
  batch.report_quarter,
  batch.month_1_name,
  batch.month_2_name,
  batch.month_3_name
from indicator_template template
cross join (
  values
    (1, 'January', 'February', 'March'),
    (2, 'April', 'May', 'June'),
    (3, 'July', 'August', 'September'),
    (4, 'October', 'November', 'December')
) as batch(report_quarter, month_1_name, month_2_name, month_3_name)
on conflict (barangay, report_year, report_quarter, slug) do nothing;

create or replace function public.set_monthly_report_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists monthly_report_updated_at on public.monthly_report;
create trigger monthly_report_updated_at
  before update on public.monthly_report
  for each row execute function public.set_monthly_report_updated_at();

alter table public.monthly_report enable row level security;

grant select, insert, update, delete on public.monthly_report to authenticated;
grant usage, select on sequence public.monthly_report_monthly_report_id_seq to authenticated;

drop policy if exists nutrigrid_monthly_report_admin_all on public.monthly_report;
create policy nutrigrid_monthly_report_admin_all on public.monthly_report
  for all to authenticated
  using (public.nutrigrid_is_admin())
  with check (public.nutrigrid_is_admin());
